ContentItem _hydrateContent({
  required String id,
  required String brandId,
  required String channelId,
  String? productId,
  required String title,
  required String description,
  required ContentFormat format,
  required ContentCategory category,
  required ContentVisibility visibility,
  required AnalysisMethod analysisMethod,
  required SensitiveTopic sensitiveTopic,
  required bool unclassifiedRiskFlag,
  required ContentStatus status,
  required String scheduledDate,
  String? publishedAt,
  required String brief,
  required String angleIdea,
  required String script,
  required String affiliateLinkUrl,
  required String verifiedDestinationUrl,
  required String linkVerifiedAt,
  required String commercialConditionsVerifiedAt,
  String? offerEndsAt,
  required String affiliateDisclosure,
  required bool aiDisclosureRequired,
  required String aiDisclosureText,
  required bool relevanceTestPassed,
  required bool editorialChecklistPassed,
  required double humanHoursLogged,
  required List<DossierSource> dossier,
  required List<String> references,
  required List<_SeedVersionInput> versions,
  ContentMetrics? metrics,
  _SeedAuthInput? authorize,
}) {
  final hash = computeContentManifestHash(
    ManifestFields(
      brandId: brandId,
      channelId: channelId,
      productId: productId,
      title: title,
      description: description,
      format: format,
      category: category,
      visibility: visibility,
      analysisMethod: analysisMethod,
      sensitiveTopic: sensitiveTopic,
      script: script,
      affiliateLinkUrl: affiliateLinkUrl,
      affiliateDisclosure: affiliateDisclosure,
      aiDisclosureRequired: aiDisclosureRequired,
      aiDisclosureText: aiDisclosureText,
    ),
  );

  return ContentItem(
    id: id,
    brandId: brandId,
    channelId: channelId,
    productId: productId,
    title: title,
    description: description,
    format: format,
    category: category,
    visibility: visibility,
    analysisMethod: analysisMethod,
    sensitiveTopic: sensitiveTopic,
    unclassifiedRiskFlag: unclassifiedRiskFlag,
    status: status,
    scheduledDate: scheduledDate,
    publishedAt: publishedAt,
    brief: brief,
    angleIdea: angleIdea,
    script: script,
    affiliateLinkUrl: affiliateLinkUrl,
    verifiedDestinationUrl: verifiedDestinationUrl,
    linkVerifiedAt: linkVerifiedAt,
    commercialConditionsVerifiedAt: commercialConditionsVerifiedAt,
    offerEndsAt: offerEndsAt,
    affiliateDisclosure: affiliateDisclosure,
    aiDisclosureRequired: aiDisclosureRequired,
    aiDisclosureText: aiDisclosureText,
    relevanceTestPassed: relevanceTestPassed,
    editorialChecklistPassed: editorialChecklistPassed,
    humanHoursLogged: humanHoursLogged,
    dossier: dossier,
    references: references,
    currentManifestHash: hash,
    authorization: authorize == null
        ? null
        : ContentAuthorization(
            type: AuthorizationType.individual,
            authorizedHash: hash,
            actor: authorize.actor,
            authorizedAt: authorize.authorizedAt,
            expiresAt: authorize.expiresAt,
            rulesVersion: authorize.rulesVersion,
            evidenceVerifiedAt: authorize.evidenceVerifiedAt,
            offerEndsAt: authorize.offerEndsAt,
          ),
    versions: versions
        .map(
          (v) => ContentVersion(
            version: v.version,
            manifestHash: v.manifestHash ?? hash,
            author: v.author,
            note: v.note,
            feedbackCategory: v.feedbackCategory,
            timestamp: v.timestamp,
            scriptSnapshot: v.scriptSnapshot,
          ),
        )
        .toList(),
    metrics: metrics,
  );
}

