function hydrateContent(
  raw: Omit<ContentItem, 'currentManifestHash' | 'versions'> & {
    versions: Array<Omit<ContentItem['versions'][number], 'manifestHash'> & { manifestHash?: string }>;
  },
  authorize?: {
    actor: string;
    authorizedAt: string;
    expiresAt: string;
    rulesVersion: string;
    evidenceVerifiedAt: string;
    offerEndsAt?: string;
  }
): ContentItem {
  const hash = computeContentManifestHash(raw);
  return {
    ...raw,
    currentManifestHash: hash,
    authorization: authorize
      ? {
          type: 'individual',
          authorizedHash: hash,
          ...authorize,
        }
      : null,
    versions: raw.versions.map((v) => ({
      ...v,
      manifestHash: v.manifestHash ?? hash,
    })),
  };
}

